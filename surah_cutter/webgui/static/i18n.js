function translatePattern(source) {
  if (uiLanguage === "ru") return source;
  const indexes = [];
  const key = source.trim().replace(/\s+/g, " ").replace(/\$\{(\d+)\}/g, (_, index) => {
    indexes.push(index); return `\$\{${indexes.length - 1}\}`;
  });
  if (!Object.hasOwn(EN, key)) return source;
  const result = EN[key].replace(/\$\{(\d+)\}/g, (_, index) => `\$\{${indexes[index]}\}`);
  return source.match(/^\s*/)[0] + result + source.match(/\s*$/)[0];
}

function t(source, ...values) {
  let pattern = typeof source === "string" ? source : source.map((part, index) => part + (index < values.length ? `\$\{${index}\}` : "")).join("");
  // Translate trusted template copy before inserting data (including Arabic text).
  if (pattern.includes("<")) {
    pattern = pattern.replace(/(^|>)([^<]*)(?=<|$)/g, (_, prefix, text) => prefix + translatePattern(text))
      .replace(/((?:aria-label|title|placeholder)=")([^"]*)(")/g, (_, prefix, text, suffix) => prefix + translatePattern(text) + suffix);
  } else pattern = translatePattern(pattern);
  return pattern.replace(/\$\{(\d+)\}/g, (_, index) => values[index]);
}

// Capture only initial UI nodes. User-created names and Quran text are never scanned.
const staticCopy = [];
function captureStaticCopy(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("script, style, [lang=ar]") || !/[А-Яа-яЁё]/.test(node.data)) continue;
    staticCopy.push({ node, source: node.data, previous: node.data });
  }
  root.querySelectorAll("*").forEach(node => {
    for (const attribute of ["title", "aria-label", "placeholder"]) {
      const source = node.getAttribute(attribute);
      if (source && /[А-Яа-яЁё]/.test(source)) staticCopy.push({ node, attribute, source, previous: source });
    }
    if (node.tagName === "TEMPLATE") captureStaticCopy(node.content);
  });
}

function setUiLanguage(language) {
  uiLanguage = language === "ru" ? "ru" : "en";
  document.documentElement.lang = uiLanguage;
  for (const entry of staticCopy) {
    const current = entry.attribute ? entry.node.getAttribute(entry.attribute) : entry.node.data;
    if (current !== entry.previous) continue; // A dynamic component owns it now.
    entry.previous = t(entry.source);
    if (entry.attribute) entry.node.setAttribute(entry.attribute, entry.previous);
    else entry.node.data = entry.previous;
  }
  document.getElementById("settingsLanguage").value = uiLanguage;
  document.documentElement.removeAttribute("data-i18n-pending");
}

// API errors can be translated without modifying their payload or diagnostic logs.
const messagePatterns = Object.entries(EN).map(([ru, en]) => {
  const pattern = text => new RegExp("^" + text.split(/(\$\{\d+\})/).map(part =>
    /^\$\{\d+\}$/.test(part) ? "([\\s\\S]*?)" : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("") + "$");
  return { ru, en, ruPattern: pattern(ru), enPattern: pattern(en) };
}).sort((a, b) => b.ru.replace(/\$\{\d+\}/g, "").length - a.ru.replace(/\$\{\d+\}/g, "").length);

function translateMessage(message) {
  if (typeof message !== "string") return message;
  const source = message.trim();
  for (const entry of messagePatterns) {
    const match = (uiLanguage === "en" ? entry.ruPattern : entry.enPattern).exec(source);
    if (!match) continue;
    const target = uiLanguage === "en" ? entry.en : entry.ru;
    const translated = target.replace(/\$\{(\d+)\}/g, (_, index) => match[Number(index) + 1]);
    return message.match(/^\s*/)[0] + translated + message.match(/\s*$/)[0];
  }
  // Prefixes used with an API error retain the translated error on language changes.
  for (const entry of messagePatterns) {
    const from = uiLanguage === "en" ? entry.ru : entry.en;
    if (from.includes("${") || !/[.:]$/.test(from) || !source.startsWith(from + " ")) continue;
    const to = uiLanguage === "en" ? entry.en : entry.ru;
    return to + " " + translateMessage(source.slice(from.length + 1));
  }
  return message;
}

